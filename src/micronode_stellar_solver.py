import numpy as np

# Physical SI Constants
C = 2.99792458e8          # m/s
G = 6.67430e-11           # m^3 kg^-1 s^-2
M_SUN = 1.989e30          # kg


def micro_node_boundary(M_node_solar: float) -> dict:
    """
    Computes boundary condition at R_node = 3 * M_node.
    """
    M_node_kg = M_node_solar * M_SUN
    R_node = (3.0 * G * M_node_kg) / (C**2)
    return {
        "M_node_solar": M_node_solar,
        "M_node_kg": M_node_kg,
        "R_node_m": R_node
    }


def ocm_viscous_force(r: float, M_node_solar: float, gamma_kappa: float = 0.01) -> float:
    """
    Calculates outward viscous force F_kappa(r) generated by central OCM node:
    F_kappa(r) = (c^4 / G) * (R_node / r)^2 * exp(- integral(gamma_kappa dr))
    """
    nb = micro_node_boundary(M_node_solar)
    R_node = nb["R_node_m"]
    
    if r < R_node:
        return 0.0
    
    planck_force = (C**4) / G
    geometric_factor = (R_node / r)**2
    damping = np.exp(-gamma_kappa * (r - R_node) / R_node)
    
    return planck_force * geometric_factor * damping


def bondi_vs_ocm_accretion(M_node_solar_arr: np.ndarray, rho_core: float = 1.0e5) -> dict:
    """
    Compares classical runaway Bondi accretion rate against OCM thermal phase reversion.
    Classical Bondi: dM/dt ~ M_node^2 (Unstable Divergence)
    OCM Net Rate: dM_net/dt = M_dot_infall - M_dot_kappa -> 0 (Stable Fixed-Point Attractor)
    """
    # Classical Bondi Rate (Arbitrary Units normalized to M_solar/yr)
    bondi_rate = 1.0e-6 * (M_node_solar_arr**2) * (rho_core / 1.0e5)
    
    # OCM Thermal Reversion Rate (Reaches fixed point equilibrium at M_eq)
    M_eq = 1.0e-6  # PBH micro-node equilibrium mass in solar units
    ocm_infall = 1.0e-5 * M_node_solar_arr / (1.0 + (M_node_solar_arr / M_eq)**2)
    ocm_outflow = 1.0e-5 * M_node_solar_arr * (M_node_solar_arr / M_eq)**2 / (1.0 + (M_node_solar_arr / M_eq)**2)
    ocm_net_rate = ocm_infall - ocm_outflow
    
    return {
        "M_node": M_node_solar_arr,
        "bondi_rate": bondi_rate,
        "ocm_net_rate": ocm_net_rate
    }


